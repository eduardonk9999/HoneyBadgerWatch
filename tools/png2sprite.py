#!/usr/bin/env python3
"""Convert PNG sprites to a firmware RGB565 header for HoneyBadgerWatch.

The firmware draws into an 8-bit paletted frame, but drawPixel() takes a
uint16_t RGB565 colour and converts it, so a plain RGB565 array blits fine
(see Texugo::draw in src/texugo.cpp). Transparency is a sentinel colour
(magenta 0xF81F) the mascot art never uses; the blitter skips those pixels.

Usage:
    python3 tools/png2sprite.py OUT.h NAME=path.png [NAME2=path2.png ...]

Run with the texugo-sprite venv's Python (it has Pillow):
    ~/Documents/texugo-sprite/.venv/bin/python tools/png2sprite.py ...
"""
import sys
from PIL import Image

KEY = 0xF81F  # transparent sentinel (magenta): never in the texugo palette


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def emit(name, path, out):
    img = Image.open(path).convert("RGBA")
    w, h = img.size
    px = img.load()
    out.append(f"constexpr int {name}_W = {w};")
    out.append(f"constexpr int {name}_H = {h};")
    out.append(f"const uint16_t {name}[{w} * {h}] = {{")
    for y in range(h):
        row = []
        for x in range(w):
            r, g, b, a = px[x, y]
            row.append(KEY if a < 128 else rgb565(r, g, b))
        out.append("    " + ", ".join(f"0x{v:04X}" for v in row) + ",")
    out.append("};")
    out.append("")


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    out_path = sys.argv[1]
    lines = [
        "// Generated by tools/png2sprite.py -- do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace Texugo {",
        "",
        "// Transparent pixels carry this sentinel; the blitter skips them.",
        "constexpr uint16_t KEY = 0xF81F;",
        "",
    ]
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        emit(name, path, lines)
    lines.append("}  // namespace Texugo")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_path} ({len(sys.argv) - 2} sprites)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
